const nav = document.querySelector('#nav');
const menu = document.querySelector('.menu');
function closeMenu() { nav.classList.remove('open'); menu.setAttribute('aria-expanded', 'false'); }
function setLanguage(language) {
  const lang = language === 'en' ? 'en' : 'zh';
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const entry = translations[element.dataset.i18n];
    if (entry) element.textContent = entry[lang];
  });
  document.querySelectorAll('[data-lang]').forEach(button => button.setAttribute('aria-pressed', String(button.dataset.lang === lang)));
  nav.setAttribute('aria-label', lang === 'en' ? 'Main navigation' : '主导航');
  document.title = lang === 'en' ? 'CCS IT · Connect Cambridge' : 'CCS IT · 用技术连接剑桥';
  document.querySelector('meta[name="description"]').content = lang === 'en' ? 'Explore CCS digital services, official events and IT team enquiries.' : '认识 CCS 的数字服务，查看官方活动渠道，了解 IT 部联系与招新信息。';
  try { localStorage.setItem('ccs-language', lang); } catch { /* Private mode: switching still works. */ }
}
document.querySelectorAll('[data-lang]').forEach(button => button.addEventListener('click', () => setLanguage(button.dataset.lang)));
menu.addEventListener('click', () => { const open = nav.classList.toggle('open'); menu.setAttribute('aria-expanded', String(open)); });
nav.querySelectorAll('a').forEach(link => link.addEventListener('click', closeMenu));
document.addEventListener('keydown', event => { if (event.key === 'Escape' && nav.classList.contains('open')) { closeMenu(); menu.focus(); } });
document.addEventListener('click', event => { if (!event.target.closest('.header')) closeMenu(); });
window.matchMedia('(min-width: 901px)').addEventListener('change', closeMenu);
let preferred = 'zh';
try { preferred = localStorage.getItem('ccs-language') || 'zh'; } catch { /* Use Chinese by default. */ }
setLanguage(preferred);
